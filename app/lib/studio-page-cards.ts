export type StudioPageKey = "digital" | "application" | "growth" | "ai";

export const STUDIO_PAGE_CARDS: Record<StudioPageKey, StudioServiceCard[]> = {
  digital: digitalExperienceStudioPageCards,
  application: applicationDevelopmentStudioPageCards,
  growth: growthBrandingStudioPageCards,
  ai: aiAndThingsStudioPageCards,
};

export function findStudioPageCard(
  studio: StudioPageKey,
  title: string
): StudioServiceCard | undefined {
  return STUDIO_PAGE_CARDS[studio].find((card) => card.title === title);
}
